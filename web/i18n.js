export function t(langCode, key, ...args) {
  const code = resolveLanguage(langCode).code;
  const pack = TRANSLATIONS[code] || TRANSLATIONS[DEFAULT_LANGUAGE];
  let template = pack[key] ?? TRANSLATIONS.en[key] ?? key;
  args.forEach((arg, idx) => {
    template = template.replaceAll(`{${idx}}`, String(arg ?? ""));
  });
  return template;
}
